#!/usr/bin/env python3
"""Generate Rosette's PowerPC opcode enum and decode tree in Zig.

Inputs (both checked in, both auditable):
    tools/ppc_isa_spec.txt      one row per instruction: encoding, form, group
    tools/ppc_decode_tree.txt   the two-level primary/extended decision tree

Outputs:
    ISA/ppc/decode/opcode.zig   Op enum + per-op metadata
    ISA/ppc/decode/table.zig    decodeOp(word) -> Op

Usage:  python3 tools/gen_ppc_decoder.py
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "tools", "ppc_isa_spec.txt")
TREE = os.path.join(ROOT, "tools", "ppc_decode_tree.txt")
OUT = os.path.join(ROOT, "ISA", "ppc", "decode")

ZIG_KEYWORDS = {
    "align", "allowzero", "and", "anyframe", "anytype", "asm", "async",
    "await", "break", "callconv", "catch", "comptime", "const", "continue",
    "defer", "else", "enum", "errdefer", "error", "export", "extern", "fn",
    "for", "if", "inline", "linksection", "noalias", "noinline", "nosuspend",
    "opaque", "or", "orelse", "packed", "pub", "resume", "return", "struct",
    "suspend", "switch", "test", "threadlocal", "try", "union", "unreachable",
    "usingnamespace", "var", "volatile", "while",
}

GROUP_NAME = {
    "I": "integer", "B": "branch", "C": "condition_register",
    "M": "memory", "F": "floating_point", "V": "vector",
}


def zig_ident(name: str) -> str:
    return '@"%s"' % name if name in ZIG_KEYWORDS else name


def load_spec():
    rows = {}
    order = []
    with open(SPEC, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            pattern, mnem, form, group, kind, fmt = line.split("|")
            rows[mnem] = {
                "pattern": int(pattern, 16),
                "form": form,
                "group": group,
                "kind": kind,
                "fmt": fmt,
            }
            order.append(mnem)
    return rows, order


def load_tree():
    """[(primary, [('hit', mnem)] | [('switch', [(a,b,s)...], [(value, mnem)...])])]"""
    cases = []
    current = None
    switch = None
    with open(TREE, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            if line.startswith("primary "):
                current = (int(line.split()[1]), [])
                cases.append(current)
                switch = None
            elif line.startswith("hit "):
                current[1].append(("hit", line.split()[1]))
                switch = None
            elif line.startswith("switch "):
                spec = line.split(None, 1)[1]
                ranges = []
                for part in spec.split(","):
                    a, b, s = part.split(":")
                    ranges.append((int(a), int(b), int(s)))
                switch = ("switch", ranges, [])
                current[1].append(switch)
            else:
                value, mnem = line.split()
                switch[2].append((int(value, 2), mnem))
    return cases


OPCODE_HEADER = '''//! PowerPC opcode identity for the Xbox 360 (Xenon) instruction set.
//!
//! Generated by tools/gen_ppc_decoder.py from tools/ppc_isa_spec.txt.
//! Do not edit by hand.
//!
//! One enum member per instruction, matching the ISA/ppc table of the same
//! name, so a decoded `Op` and its ISA contract are the same identity. The
//! trailing `x` on a mnemonic is PowerPC's record-bit family marker: `addx`
//! covers add, add., addo, and addo., which differ only in the Rc and OE bits.

const std = @import("std");

pub const Group = enum(u8) {
    integer,
    branch,
    condition_register,
    memory,
    floating_point,
    vector,
};

pub const Form = enum(u8) {
'''


def emit_opcode(rows, order):
    forms = sorted({rows[m]["form"] for m in order})
    lines = [OPCODE_HEADER]
    for form in forms:
        lines.append("    %s," % form.lower())
    lines.append("};\n")
    lines.append("pub const Op = enum(u16) {")
    lines.append("    invalid,")
    for mnem in order:
        lines.append("    %s," % zig_ident(mnem))
    lines.append("")
    lines.append("    pub fn mnemonic(self: Op) []const u8 {")
    lines.append("        return @tagName(self);")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn info(self: Op) Info {")
    lines.append("        return op_info[@intFromEnum(self)];")
    lines.append("    }")
    lines.append("")
    lines.append("    pub fn isValid(self: Op) bool {")
    lines.append("        return self != .invalid;")
    lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("pub const Info = struct {")
    lines.append("    /// The encoding with every variable field zeroed.")
    lines.append("    pattern: u32,")
    lines.append("    form: Form,")
    lines.append("    group: Group,")
    lines.append("    /// True when this instruction ends a basic block.")
    lines.append("    ends_block: bool,")
    lines.append("    /// True when bit 31 is the record bit (updates CR0/CR1/CR6).")
    lines.append("    has_rc: bool,")
    lines.append("    /// True when bit 21 is the overflow-enable bit (updates XER.OV/SO).")
    lines.append("    has_oe: bool,")
    lines.append("    /// True when bit 31 is the link bit (writes LR).")
    lines.append("    has_lk: bool,")
    lines.append("")
    lines.append("    pub fn primary(self: Info) u6 {")
    lines.append("        return @truncate(self.pattern >> 26);")
    lines.append("    }")
    lines.append("};")
    lines.append("")
    lines.append("const op_info = [_]Info{")
    lines.append("    .{ .pattern = 0, .form = .x, .group = .integer, "
                 ".ends_block = false, .has_rc = false, .has_oe = false, .has_lk = false },")
    for mnem in order:
        r = rows[mnem]
        lines.append(
            "    .{ .pattern = 0x%08x, .form = .%s, .group = .%s, "
            ".ends_block = %s, .has_rc = %s, .has_oe = %s, .has_lk = %s },"
            % (r["pattern"], r["form"].lower(), GROUP_NAME[r["group"]],
               "true" if r["kind"] == "Sync" else "false",
               "true" if "[Rc]" in r["fmt"] else "false",
               "true" if "[OE]" in r["fmt"] else "false",
               "true" if "[LK]" in r["fmt"] else "false"))
    lines.append("};")
    lines.append("")
    lines.append('test "every opcode carries metadata" {')
    lines.append("    try std.testing.expectEqual(@as(usize, %d), op_info.len);"
                 % (len(order) + 1))
    lines.append("    try std.testing.expect(!Op.invalid.isValid());")
    lines.append("    const add = Op.addx.info();")
    lines.append("    try std.testing.expectEqual(@as(u6, 31), add.primary());")
    lines.append("    try std.testing.expect(add.has_rc and add.has_oe);")
    lines.append("    try std.testing.expectEqual(Form.xo, add.form);")
    lines.append("    try std.testing.expectEqual(Group.integer, add.group);")
    lines.append("    try std.testing.expect(Op.bx.info().ends_block);")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


TABLE_HEADER = '''//! PowerPC primary/extended decode tree.
//!
//! Generated by tools/gen_ppc_decoder.py from tools/ppc_decode_tree.txt.
//! Do not edit by hand.
//!
//! PowerPC instructions are a fixed four bytes: the 6-bit primary opcode picks
//! a case, and the case narrows on one or more extended-opcode bit ranges.
//! VMX128 shares primaries 4, 5, and 6 with AltiVec, so the order of the
//! switches inside those primaries is load-bearing - the narrower VMX128
//! switch has to run before the AltiVec one.

const std = @import("std");
const opcode = @import("opcode.zig");

pub const Op = opcode.Op;

/// PowerPC bit numbering: bit 0 is the most significant bit of the word.
pub inline fn extractBits(word: u32, comptime a: u5, comptime b: u5) u32 {
    const width = b - a + 1;
    return (word >> (31 - b)) & ((@as(u32, 1) << width) - 1);
}

pub fn decodeOp(word: u32) Op {
'''


def emit_table(cases):
    lines = [TABLE_HEADER]
    lines.append("    switch (extractBits(word, 0, 5)) {")
    for primary, actions in cases:
        if len(actions) == 1 and actions[0][0] == "hit":
            lines.append("        %d => return .%s,"
                         % (primary, zig_ident(actions[0][1])))
            continue
        lines.append("        %d => {" % primary)
        for action in actions:
            if action[0] == "hit":
                lines.append("            return .%s;" % zig_ident(action[1]))
                continue
            _, ranges, entries = action
            terms = " | ".join(
                "(extractBits(word, %d, %d) << %d)" % (a, b, s)
                for a, b, s in ranges)
            lines.append("            switch (%s) {" % terms)
            for value, mnem in entries:
                lines.append("                %d => return .%s,"
                             % (value, zig_ident(mnem)))
            lines.append("                else => {},")
            lines.append("            }")
        lines.append("            return .invalid;")
        lines.append("        },")
    lines.append("        else => return .invalid,")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def emit_table_tests(rows, order, cases):
    """Round-trip every table pattern through the generated decoder."""
    lines = ['test "every encoding pattern decodes back to its own opcode" {']
    lines.append("    const cases = [_]struct { word: u32, op: Op }{")
    for mnem in order:
        lines.append("        .{ .word = 0x%08x, .op = .%s },"
                     % (rows[mnem]["pattern"], zig_ident(mnem)))
    lines.append("    };")
    lines.append("    for (cases) |c| {")
    lines.append("        const got = decodeOp(c.word);")
    lines.append("        if (got != c.op) {")
    lines.append("            std.debug.print(\"word=0x{x:0>8} expected {s} got {s}\\n\","
                 " .{ c.word, @tagName(c.op), @tagName(got) });")
    lines.append("            return error.DecodeMismatch;")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append('test "an unallocated primary opcode decodes to invalid" {')
    used = sorted({p for p, _ in cases})
    unused = [p for p in range(64) if p not in used]
    lines.append("    const unallocated = [_]u32{%s};"
                 % ", ".join(str(p) for p in unused[:8]))
    lines.append("    for (unallocated) |primary| {")
    lines.append("        try std.testing.expectEqual(Op.invalid, decodeOp(primary << 26));")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    rows, order = load_spec()
    cases = load_tree()

    covered = set()
    for _, actions in cases:
        for action in actions:
            if action[0] == "hit":
                covered.add(action[1])
            else:
                covered.update(m for _, m in action[2])
    missing = sorted(set(order) - covered)
    if missing:
        raise SystemExit("decode tree misses %d instruction(s): %s"
                         % (len(missing), ", ".join(missing[:10])))
    stray = sorted(covered - set(order))
    if stray:
        raise SystemExit("decode tree names unknown instruction(s): %s"
                         % ", ".join(stray[:10]))

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "opcode.zig"), "w", encoding="utf-8") as fh:
        fh.write(emit_opcode(rows, order))
    with open(os.path.join(OUT, "table.zig"), "w", encoding="utf-8") as fh:
        fh.write(emit_table(cases) + emit_table_tests(rows, order, cases))

    print("opcodes: %d  primaries: %d  switches: %d"
          % (len(order), len(cases),
             sum(1 for _, a in cases for x in a if x[0] == "switch")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
