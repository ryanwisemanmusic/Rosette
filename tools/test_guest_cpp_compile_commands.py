#!/usr/bin/env python3
"""Read compilation metadata on stdin; syntax-check only, never build/run PE.

Usage: jq '.' compile_commands.json | python3 this_script.py FRESH_WRAPPER
The wrapper must be generated by Rosette's support-only operation against
the same immutable source root that the compilation metadata names.
"""
import json
import shlex
import subprocess
import sys

targets = (
    "src/xenia/base/profiling.cc",
    "src/xenia/base/threading_win.cc",
    "src/xenia/ui/windowed_app_context_win.cc",
    "src/xenia/hid/xinput/xinput_input_driver.cc",
    "src/xenia/ui/windowed_app_main_win.cc",
    "src/xenia/base/main_init_win.cc",
    "src/xenia/gpu/command_processor.cc",
    "src/xenia/gpu/vulkan/vulkan_command_processor.cc",
    "src/xenia/gpu/draw_util.cc",
)

def main():
    if len(sys.argv) != 2:
        raise SystemExit("expected fresh Rosette wrapper path")
    commands = json.load(sys.stdin)
    checked = 0
    for target in targets:
        matches = [row for row in commands if row["file"].endswith("/" + target)
                   and "Release" in row.get("command", "")]
        if len(matches) != 1:
            raise SystemExit(f"expected one Release command for {target}, got {len(matches)}")
        row = matches[0]
        args = shlex.split(row["command"])[1:]
        sanitized = [sys.argv[1]]
        index = 0
        while index < len(args):
            arg = args[index]
            if arg in ("-o", "-MF", "-MT", "-MQ", "-MJ"):
                index += 2
                continue
            if arg in ("-c", "-MD", "-MMD", "-MP"):
                index += 1
                continue
            if arg.startswith(("-save-temps", "-serialize-diagnostics", "-fmodules")):
                raise SystemExit(f"unexpected file-producing option: {arg}")
            sanitized.append(arg)
            index += 1
        sanitized.append("-fsyntax-only")
        print(f"Compile-only: {target}", flush=True)
        subprocess.run(sanitized, cwd=row["directory"], check=True)
        checked += 1
    print(f"Real Xenia translation units: PASS ({checked}; no objects, PE or source writes)")

if __name__ == "__main__":
    main()
