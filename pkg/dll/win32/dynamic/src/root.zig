/// This package never claims a concrete DLL. The library-inventory surface
/// gate decides whether a non-empty DLL is allowed to use this compatibility
/// bucket; the empty DLL case is the intended name-only path.
pub fn matches(_: []const u8) bool {
    return false;
}

pub fn hasDegradedImport(function_name: []const u8) bool {
    for (degraded_imports) |known| {
        if (std.mem.eql(u8, function_name, known)) return true;
    }
    return false;
}

test "dynamic compatibility keeps the complete known-name inventory" {
    try std.testing.expect(!matches("kernel32.dll"));
    try std.testing.expect(hasDegradedImport("LibK_GetVersion"));
    try std.testing.expect(hasDegradedImport("memchr"));
    try std.testing.expect(!hasDegradedImport("__not_in_this_dll__"));
}
