/// The standard package entry point, so the runtime contract log can check
/// this package the same way it checks every other one.
///
/// Verifying the sort is not ceremony: `lookup` is a binary search, and a
/// table that is merely *mostly* sorted makes it miss entries rather than
/// fail. A miss reports an ordinal as unpublished, which reads as a title
/// importing something the kernel does not have.
pub fn contractIsWellFormed() bool {
    return tablesAreWellFormed();
}

test "the tables are sorted and duplicate free" {
    // The precondition the binary search depends on. A mostly-sorted table
    // makes lookup miss entries rather than fail loudly.
    try std.testing.expect(tablesAreWellFormed());
}

test "the tables carry the console's whole export surface" {
    try std.testing.expectEqual(@as(usize, 922), xboxkrnl_exports.len);
    try std.testing.expectEqual(@as(usize, 1736), xam_exports.len);
    try std.testing.expectEqual(@as(usize, 255), xbdm_exports.len);
    // 2913 total, against the sixteen lib/gpu/kernel_surface.zig carried.
    const total = xboxkrnl_exports.len + xam_exports.len + xbdm_exports.len;
    try std.testing.expectEqual(@as(usize, 2913), total);
}

