test "an unpublished ordinal reports nothing rather than a fabricated name" {
    // A placeholder like "ordinal_2000" reads as a real export in a log and
    // sends someone looking for something that does not exist.
    try std.testing.expect(lookup(.xboxkrnl, 0) == null);
    try std.testing.expect(nameOf(.xboxkrnl, 0xFFFF) == null);
    try std.testing.expect(nameOf(.xam, 0) == null);
}

test "lookup finds the first, last and interior entries" {
    // Binary search boundary cases: an off-by-one in the loop typically loses
    // exactly the first or last entry, and nothing else.
    try std.testing.expectEqualStrings("DbgBreakPoint", nameOf(.xboxkrnl, 0x0001).?);
    const last = xboxkrnl_exports[xboxkrnl_exports.len - 1];
    try std.testing.expectEqualStrings(last.name, nameOf(.xboxkrnl, last.ordinal).?);
    try std.testing.expectEqualStrings("NetDll_WSAStartup", nameOf(.xam, 0x0001).?);
}

test "every entry in every table is reachable through lookup" {
    // The exhaustive version of the boundary test: if the search is wrong for
    // any ordinal, this finds it rather than hoping a spot check does.
    inline for (.{ Module.xboxkrnl, Module.xam, Module.xbdm }) |module| {
        for (module.table()) |entry| {
            const found = lookup(module, entry.ordinal) orelse return error.TestUnexpectedResult;
            try std.testing.expectEqual(entry.ordinal, found.ordinal);
            try std.testing.expectEqualStrings(entry.name, found.name);
        }
    }
}

test "names resolve back to their ordinals" {
    try std.testing.expectEqual(@as(u16, 0x1C3), ordinalOf(.xboxkrnl, "VdInitializeRingBuffer").?);
    try std.testing.expectEqual(@as(u16, 0x25B), ordinalOf(.xboxkrnl, "VdSwap").?);
    // A name from another module does not resolve in this one.
    try std.testing.expect(ordinalOf(.xboxkrnl, "NetDll_WSAStartup") == null);
    try std.testing.expect(ordinalOf(.xboxkrnl, "NotAnExport") == null);
}

test "the modules are distinct namespaces" {
    // Ordinal 1 exists in all three and means something different in each.
    // Resolving an import against the wrong module binds the wrong function,
    // and the call succeeds — it just does something unrelated.
    const krnl = nameOf(.xboxkrnl, 1).?;
    const xam = nameOf(.xam, 1).?;
    const xbdm = nameOf(.xbdm, 1).?;
    try std.testing.expect(!std.mem.eql(u8, krnl, xam));
    try std.testing.expect(!std.mem.eql(u8, krnl, xbdm));
}

test "the debug monitor is not a retail module" {
    // A retail title importing from xbdm is either a debug build or a
    // mis-parsed import table, and those are worth telling apart.
    try std.testing.expect(Module.xboxkrnl.isRetail());
    try std.testing.expect(Module.xam.isRetail());
    try std.testing.expect(!Module.xbdm.isRetail());
    try std.testing.expectEqualStrings("xboxkrnl.exe", Module.xboxkrnl.moduleName());
    try std.testing.expectEqualStrings("xam.xex", Module.xam.moduleName());
}

test "the video surface is a small part of the kernel" {
    // 73 Vd exports out of 922, under eight percent. Worth stating: a title
    // that imports a dozen of them has imported most of the video surface it
    // will ever need, so a low count there is not evidence of a truncated
    // import table.
    const video = countWithPrefix(.xboxkrnl, "Vd");
    try std.testing.expectEqual(@as(usize, 73), video);
    try std.testing.expect(video < xboxkrnl_exports.len / 10);
}

