//! Route-independent: the Xbox 360 kernel's export ordinal tables.
//!
//! Every export `xboxkrnl.exe`, `xam.xex` and `xbdm.xex` publish, by ordinal,
//! with its name and whether it is a function or a variable. 2913 entries,
//! transcribed from the console's own export tables. They were fixed when the
//! kernel shipped; there is one copy and no route mirror.
//!
//! ## Why an ordinal map earns its size
//!
//! A title imports kernel exports **by ordinal, not by name**. The XEX import
//! table contains numbers, so every diagnostic downstream of it either carries
//! a number or carries whatever name the reader happened to know. Rosette
//! previously knew sixteen — the GPU-facing ones hand-entered in
//! `lib/gpu/kernel_surface.zig` — which meant an import of ordinal 0x102 was
//! reported as `0x102` and the reader had to go and look it up.
//!
//! That is not a cosmetic problem. `KERNEL SURFACE` reported the kernel export
//! layer at 28% and `kernel export binding` as *untested*, and both of those
//! are consequences of not being able to name what a title imported. A map
//! turns "this title imported 340 ordinals" into "this title imported 340
//! exports, of which these are the video ones and these are unimplemented".
//!
//! ## Why in pkg and not beside the runtime
//!
//! Sixteen ordinals in `lib/gpu/kernel_surface.zig` put an immutable console
//! table next to live import state, which is the same mistake
//! `pkg/common/xenos/register-map` was created to undo for GPU registers. The
//! table cannot change while a process runs, or between hosts.
//!
//! ## What this package is not
//!
//! * It is not an import table. It cannot say a title imported anything; only
//!   the loader that read the XEX knows that.
//! * It is not an implementation status. `kind` distinguishes a function from a
//!   variable, which is an ABI fact. Whether Xenia *implements* a given export
//!   is a property of Xenia's build, changes between versions, and is
//!   deliberately absent.
//! * It resolves nothing. An ordinal's address is a runtime fact.

const std = @import("std");

pub const Kind = enum(u8) {
    function,
    /// A variable export is a *slot*, not code. The title reads or writes the
    /// address; calling one is a bug that presents as a jump into data.
    variable,
};

pub const Export = struct {
    ordinal: u16,
    name: []const u8,
    kind: Kind,
};

/// The kernel modules a title can import from.
pub const Module = enum {
    xboxkrnl,
    xam,
    xbdm,

    pub fn moduleName(self: Module) []const u8 {
        return switch (self) {
            .xboxkrnl => "xboxkrnl.exe",
            .xam => "xam.xex",
            .xbdm => "xbdm.xex",
        };
    }

    /// Whether this module is present on a retail console.
    ///
    /// `xbdm` is the debug monitor and exists only on a devkit. A retail title
    /// importing from it is either a debug build or a mis-parsed import table,
    /// and the two are worth telling apart.
    pub fn isRetail(self: Module) bool {
        return self != .xbdm;
    }

    pub fn table(self: Module) []const Export {
        return switch (self) {
            .xboxkrnl => &xboxkrnl_exports,
            .xam => &xam_exports,
            .xbdm => &xbdm_exports,
        };
    }
};

/// Look an ordinal up in a module's table.
///
/// Binary search: the tables are sorted by ordinal and a linear scan over 1736
/// entries on an import-resolution path is the kind of cost that only shows up
/// once a title imports several hundred of them.
pub fn lookup(module: Module, ordinal: u16) ?Export {
    const entries = module.table();
    var low: usize = 0;
    var high: usize = entries.len;
    while (low < high) {
        const middle = low + (high - low) / 2;
        const candidate = entries[middle];
        if (candidate.ordinal == ordinal) return candidate;
        if (candidate.ordinal < ordinal) low = middle + 1 else high = middle;
    }
    return null;
}

/// The name for an ordinal, or null when the module does not publish one.
///
/// Null rather than a placeholder string: a fabricated name like "ordinal_258"
/// reads as a real export in a log and sends someone looking for it.
pub fn nameOf(module: Module, ordinal: u16) ?[]const u8 {
    const entry = lookup(module, ordinal) orelse return null;
    return entry.name;
}

/// Find an export by name, across one module.
pub fn ordinalOf(module: Module, name: []const u8) ?u16 {
    for (module.table()) |entry| {
        if (std.mem.eql(u8, entry.name, name)) return entry.ordinal;
    }
    return null;
}

/// Whether an ordinal names a variable rather than a function.
///
/// The distinction that matters at the import boundary: a variable export is a
/// slot the title reads, and binding it as though it were code produces a jump
/// into data at whatever moment the title first dereferences it.
pub fn isVariable(module: Module, ordinal: u16) bool {
    const entry = lookup(module, ordinal) orelse return false;
    return entry.kind == .variable;
}

/// Exports whose names begin with `prefix`, counted.
///
/// Used to answer "how much of the video surface did this title import" without
/// the caller needing its own copy of the naming convention.
pub fn countWithPrefix(module: Module, prefix: []const u8) usize {
    var count: usize = 0;
    for (module.table()) |entry| {
        if (std.mem.startsWith(u8, entry.name, prefix)) count += 1;
    }
    return count;
}

/// Every table is sorted ascending with no duplicate ordinal.
///
/// The precondition `lookup`'s binary search depends on. A table that is merely
/// *mostly* sorted makes the search miss entries rather than fail, so this is
/// checked rather than assumed.
pub fn tablesAreWellFormed() bool {
    inline for (.{ xboxkrnl_exports, xam_exports, xbdm_exports }) |entries| {
        if (entries.len == 0) return false;
        var previous: u16 = 0;
        var first = true;
        for (entries) |entry| {
            if (!first and entry.ordinal <= previous) return false;
            previous = entry.ordinal;
            first = false;
        }
    }
    return true;
}

