const std = @import("std");
const types = @import("types.zig");

const BatCommand = types.BatCommand;
const BatError = types.BatError;
const CommandKind = types.CommandKind;
const Redirect = types.Redirect;

/// Translates Windows .bat script content to POSIX shell or Makefile recipes.
pub const BatTranslator = struct {
    allocator: std.mem.Allocator,
    commands: std.ArrayListUnmanaged(BatCommand),

    pub fn init(allocator: std.mem.Allocator) BatTranslator {
        return .{
            .allocator = allocator,
            .commands = .{ .items = &.{}, .capacity = 0 },
        };
    }

    pub fn deinit(self: *BatTranslator) void {
        self.commands.deinit(self.allocator);
    }

    // ---------------------------------------------------------------- //
    //  Parsing (file I/O handled by main.zig)
    // ---------------------------------------------------------------- //

    /// Parse a blob of .bat text into structured commands.
    pub fn parse(self: *BatTranslator, text: []const u8) !void {
        self.commands.clearAndFree(self.allocator);
        var lines = std.mem.splitScalar(u8, text, '\n');
        while (lines.next()) |raw_line| {
            if (parseLine(raw_line)) |cmd| {
                try self.commands.append(self.allocator, cmd);
            }
        }
    }

    // ---------------------------------------------------------------- //
    //  Shell output — builds into caller-provided buffer
    // ---------------------------------------------------------------- //

    /// Generate a POSIX shell script into `out`.
    pub fn toShell(self: *const BatTranslator, shebang: bool, out: *std.ArrayListUnmanaged(u8)) !void {
        if (shebang) {
            try out.appendSlice(self.allocator, "#!/bin/sh\n");
            try out.appendSlice(self.allocator, "# Generated by lib/processor/bat_processor/translator\n\n");
        }
        for (self.commands.items) |cmd| {
            try cmdToShellBuf(cmd, out, self.allocator);
        }
    }

    /// Generate a Makefile recipe into `out`.
    pub fn toMakefile(
        self: *const BatTranslator,
        target: []const u8,
        deps: []const []const u8,
        out: *std.ArrayListUnmanaged(u8),
    ) !void {
        try out.appendSlice(self.allocator, "# Generated by lib/processor/bat_processor/translator\n\n");
        try out.appendSlice(self.allocator, target);
        if (deps.len > 0) {
            try out.appendSlice(self.allocator, ": ");
            for (deps, 0..) |dep, i| {
                if (i > 0) try out.appendSlice(self.allocator, " ");
                try out.appendSlice(self.allocator, dep);
            }
        } else {
            try out.appendSlice(self.allocator, ":");
        }
        try out.appendSlice(self.allocator, "\n\t@echo \"  BATGEN  ");
        try out.appendSlice(self.allocator, target);
        try out.appendSlice(self.allocator, "\"\n");

        for (self.commands.items) |cmd| {
            var line_buf: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
            defer line_buf.deinit(self.allocator);
            try cmdToShellBuf(cmd, &line_buf, self.allocator);
            const shell_line = line_buf.items;

            if (shell_line.len == 0) continue;
            if (shell_line[0] == '#') {
                try out.appendSlice(self.allocator, "\t");
                try out.appendSlice(self.allocator, shell_line);
            } else {
                if (cmd.suppress) try out.appendSlice(self.allocator, "\t@");
                if (!cmd.suppress) try out.appendSlice(self.allocator, "\t");
                // $$ escaping for Make
                for (shell_line) |ch| {
                    if (ch == '$') {
                        try out.appendSlice(self.allocator, "$$");
                    } else {
                        try out.append(self.allocator, ch);
                    }
                }
                try out.append(self.allocator, '\n');
            }
        }
    }
};

