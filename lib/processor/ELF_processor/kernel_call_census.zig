test "a module's whole coverage is the sum of its subsystems" {
    var census = Census{};
    defer census.deinit(testing.allocator);
    armVideoMode(&census, testing.allocator, 0x1409cb000);
    _ = census.arm(testing.allocator, TRAMPOLINE_SWAP, 0x1409cc000);
    _ = census.arm(testing.allocator, TRAMPOLINE_READ_FILE, 0x1409ce000);

    const whole = coverageForModule(&census, .xboxkrnl);
    var summed = CoverageRow{ .module = .xboxkrnl, .subsystem = .other };
    inline for (@typeInfo(shim_map.Subsystem).@"enum".fields) |field| {
        const row = coverageFor(&census, .xboxkrnl, @enumFromInt(field.value));
        summed.published += row.published;
        summed.implemented += row.implemented;
    }
    // A classification that dropped a name, or counted one twice, shows up
    // here and nowhere else.
    try testing.expectEqual(whole.published, summed.published);
    try testing.expectEqual(whole.implemented, summed.implemented);
    try testing.expectEqual(@as(u32, 3), whole.implemented);
    try testing.expect(whole.published > 900);
}

