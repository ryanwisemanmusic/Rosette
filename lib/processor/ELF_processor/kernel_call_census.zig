test "a trampoline is armed once and counted from the call path" {
    var census = Census{};
    defer census.deinit(testing.allocator);
    armVideoMode(&census, testing.allocator, 0x1409cb000);
    // Arming twice must not take two slots; the caller offers the whole
    // symbol table and a duplicate in it would inflate the census.
    armVideoMode(&census, testing.allocator, 0x1409cb000);
    try testing.expectEqual(@as(u32, 1), census.armed);
    try testing.expectEqual(@as(u32, 1), census.armed_trampolines);
    try testing.expect(census.isArmed("VdQueryVideoMode"));

    try testing.expectEqual(@as(u32, 0), census.note(0x1409cb008, 10));
    try testing.expectEqual(@as(u64, 0), census.total_calls);

    const slot = census.note(0x1409cb000, 4242);
    try testing.expect(slot != 0);
    try testing.expectEqual(@as(u64, 1), census.total_calls);
