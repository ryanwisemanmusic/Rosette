fn translateToShell(arena: std.mem.Allocator, src: []const u8) ![]const u8 {
    var translator = Ps1Translator.init(arena);
    try translator.parse(src);

    var out: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
    try translator.toShell(true, &out);
    return out.items;
}

