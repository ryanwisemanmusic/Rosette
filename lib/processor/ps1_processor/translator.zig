const TranslateError = error{OutOfMemory};

fn cmdToShellBuf(cmd: Ps1Command, out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator) TranslateError!void {
    switch (cmd.kind) {
        .comment => {
            try out.appendSlice(allocator, "# ");
            try out.appendSlice(allocator, cmd.text);
            try out.append(allocator, '\n');
        },
        .block_end => {
            try out.appendSlice(allocator, "fi\n");
        },
        .variable => try translateVariable(cmd, out, allocator),
        .if_not_path => try translateIfPath(cmd, out, allocator, true),
        .if_path => try translateIfPath(cmd, out, allocator, false),
        .command => try translateCommand(cmd, out, allocator),
    }
}

/// `$name = value` — with Join-Path collapsing to `base/sub`.
fn translateVariable(cmd: Ps1Command, out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator) !void {
    var quoted: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
    defer quoted.deinit(allocator);
    try shQuote(cmd.value, &quoted, allocator);

    if (indexOf(quoted.items, "Join-Path") != null) {
        if (matchJoinPath(quoted.items)) |jp| {
            try out.appendSlice(allocator, cmd.name);
            try out.appendSlice(allocator, "=\"");
            try shQuote(jp.base, out, allocator);
            try out.append(allocator, '/');
            try shQuote(jp.sub, out, allocator);
            try out.appendSlice(allocator, "\"\n");
            return;
        }
    }

    try out.appendSlice(allocator, cmd.name);
    try out.appendSlice(allocator, "=\"");
    try out.appendSlice(allocator, quoted.items);
    try out.appendSlice(allocator, "\"\n");
}

/// Matches `Join-Path <base> <sub>` where both tokens are `\S+`.
fn matchJoinPath(s: []const u8) ?struct { base: []const u8, sub: []const u8 } {
    const pos = indexOf(s, "Join-Path") orelse return null;
    var rest = trimLeft(s[pos + "Join-Path".len ..], " \t");
    const base_end = indexOfScalar(rest, ' ') orelse rest.len;
    if (base_end == 0) return null;
    const base = rest[0..base_end];
    rest = trimLeft(rest[base_end..], " \t");
    const sub_end = indexOfScalar(rest, ' ') orelse rest.len;
    if (sub_end == 0) return null;
    return .{ .base = base, .sub = rest[0..sub_end] };
}

/// `if [ -e "path" ]; then ... fi` (or `! -e` for the -not variant).
/// The inline body is a single line, re-parsed and translated.
fn translateIfPath(cmd: Ps1Command, out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator, comptime negated: bool) TranslateError!void {
    var quoted: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
    defer quoted.deinit(allocator);
    try shQuote(cmd.path, &quoted, allocator);

    var body_buf: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
    defer body_buf.deinit(allocator);
    if (cmd.body.len != 0) {
        if (try parseLine(allocator, cmd.body)) |body_cmd| {
            try cmdToShellBuf(body_cmd, &body_buf, allocator);
        }
    }

    const negate = if (negated) "! " else "";
    if (body_buf.items.len != 0) {
        try out.appendSlice(allocator, "if [ ");
        try out.appendSlice(allocator, negate);
        try out.appendSlice(allocator, "-e \"");
        try out.appendSlice(allocator, quoted.items);
        try out.appendSlice(allocator, "\" ]; then\n  ");
        try out.appendSlice(allocator, body_buf.items);
        try out.appendSlice(allocator, "fi\n");
    } else {
        try out.appendSlice(allocator, "if [ ");
        try out.appendSlice(allocator, negate);
        try out.appendSlice(allocator, "-e \"");
        try out.appendSlice(allocator, quoted.items);
        try out.appendSlice(allocator, "\" ]; then\n");
    }
}

fn translateCommand(cmd: Ps1Command, out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator) !void {
    const command = cmd.command;
    const args = cmd.args;

    // Write-Host / Write-Output / Write-Warning / Write-Error
    if (std.ascii.eqlIgnoreCase(command, "Write-Host") or
        std.ascii.eqlIgnoreCase(command, "Write-Output") or
        std.ascii.eqlIgnoreCase(command, "Write-Warning") or
        std.ascii.eqlIgnoreCase(command, "Write-Error"))
    {
        var quoted: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        defer quoted.deinit(allocator);
        try shQuote(args, &quoted, allocator);
        var clean: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        defer clean.deinit(allocator);
        try stripForegroundColor(quoted.items, &clean, allocator);
        try out.appendSlice(allocator, "printf '%s\\n' \"");
        try out.appendSlice(allocator, std.mem.trim(u8, clean.items, " \t"));
        try out.appendSlice(allocator, "\"\n");
        return;
    }

    // New-Item -ItemType Directory
    if (std.ascii.eqlIgnoreCase(command, "New-Item") and indexOf(args, "-ItemType Directory") != null) {
        var quoted: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        defer quoted.deinit(allocator);
        if (matchFlagPath(args, "-Path")) |path_token| {
            try shQuote(path_token, &quoted, allocator);
            try out.appendSlice(allocator, "mkdir -p \"");
            try out.appendSlice(allocator, quoted.items);
            try out.appendSlice(allocator, "\"\n");
            return;
        }
        try out.appendSlice(allocator, "# (untranslated New-Item)\n");
        return;
    }

    // mkdir
    if (std.ascii.eqlIgnoreCase(command, "mkdir")) {
        var quoted: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        defer quoted.deinit(allocator);
        try shQuote(args, &quoted, allocator);
        try out.appendSlice(allocator, "mkdir -p \"");
        try out.appendSlice(allocator, quoted.items);
        try out.appendSlice(allocator, "\"\n");
        return;
    }

    // Move-Item
    if (std.ascii.eqlIgnoreCase(command, "Move-Item")) {
        const src = matchFlagPath(args, "-Path") orelse "";
        const dst = matchFlagPath(args, "-Destination") orelse "";
        if (src.len != 0 and dst.len != 0) {
            var src_q: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
            var dst_q: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
            defer src_q.deinit(allocator);
            defer dst_q.deinit(allocator);
            try shQuote(src, &src_q, allocator);
            try shQuote(dst, &dst_q, allocator);
            try out.appendSlice(allocator, "mv -f \"");
            try out.appendSlice(allocator, src_q.items);
            try out.appendSlice(allocator, "\" \"");
            try out.appendSlice(allocator, dst_q.items);
            try out.appendSlice(allocator, "\"\n");
            return;
        }
        try out.appendSlice(allocator, "# (untranslated Move-Item)\n");
        return;
    }

    // Remove-Item
    if (std.ascii.eqlIgnoreCase(command, "Remove-Item")) {
        var quoted: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        defer quoted.deinit(allocator);
        const path_token = matchFlagPath(args, "-Path") orelse args;
        try shQuote(path_token, &quoted, allocator);
        try out.appendSlice(allocator, "rm -rf \"");
        try out.appendSlice(allocator, quoted.items);
        try out.appendSlice(allocator, "\"\n");
        return;
    }

    // & <script> / .\ <script> invocation
    if (command[0] == '&' or startsWith(command, ".\\")) {
        const cmd_name = if (command[0] == '&') trimLeft(command[1..], " \t") else command;
        var name_q: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        var args_q: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
        defer name_q.deinit(allocator);
        defer args_q.deinit(allocator);
        try shQuote(cmd_name, &name_q, allocator);
        try shQuote(args, &args_q, allocator);
        try out.appendSlice(allocator, name_q.items);
        try out.append(allocator, ' ');
        try out.appendSlice(allocator, args_q.items);
        try out.append(allocator, '\n');
        return;
    }

    // Untranslated fallthrough
    try out.appendSlice(allocator, "# (untranslated) ");
    try out.appendSlice(allocator, trimRight(cmd.raw, " \t\r"));
    try out.append(allocator, '\n');
}

// ==================================================================== //
//  Quoting / small transforms
// ==================================================================== //

/// POSIX-shell quote for a value, applying the Python `_sh_quote` rules:
/// strip outer quotes, then replace `$PSScriptRoot` / `$scriptDir` with
/// `$(dirname "$0")`.
fn shQuote(s: []const u8, out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator) !void {
    var src = s;
    if (src.len >= 2 and
        ((src[0] == '"' and src[src.len - 1] == '"') or
            (src[0] == '\'' and src[src.len - 1] == '\'')))
    {
        src = src[1 .. src.len - 1];
    }
    var i: usize = 0;
    while (i < src.len) {
        if (std.mem.startsWith(u8, src[i..], "$PSScriptRoot")) {
            try out.appendSlice(allocator, "$(dirname \"$0\")");
            i += "$PSScriptRoot".len;
        } else if (std.mem.startsWith(u8, src[i..], "$scriptDir")) {
            try out.appendSlice(allocator, "$(dirname \"$0\")");
            i += "$scriptDir".len;
        } else {
            try out.append(allocator, src[i]);
            i += 1;
        }
    }
}

/// Remove a `-ForegroundColor <token>` clause from `s`.
fn stripForegroundColor(s: []const u8, out: *std.ArrayListUnmanaged(u8), allocator: std.mem.Allocator) !void {
    var i: usize = 0;
    while (i < s.len) {
        if (startsWithIgnoreCase(s[i..], "-ForegroundColor")) {
            var j = i + "-ForegroundColor".len;
            while (j < s.len and (s[j] == ' ' or s[j] == '\t')) j += 1;
            while (j < s.len and s[j] != ' ' and s[j] != '\t') j += 1;
            i = j;
            continue;
        }
        try out.append(allocator, s[i]);
        i += 1;
    }
}

/// Match a `-Flag <token>` pair in `s`, returning the token after the flag.
fn matchFlagPath(s: []const u8, comptime flag: []const u8) ?[]const u8 {
    var i: usize = 0;
    while (i < s.len) {
        const remaining = s[i..];
        if (startsWithIgnoreCase(remaining, flag)) {
            var j = i + flag.len;
            while (j < s.len and (s[j] == ' ' or s[j] == '\t')) j += 1;
            if (j >= s.len) return null;
            const token_start = j;
            while (j < s.len and s[j] != ' ' and s[j] != '\t') j += 1;
            return s[token_start..j];
        }
        i += 1;
    }
    return null;
}

// ==================================================================== //
//  Owned-string helper
// ==================================================================== //

fn isOwnedComment(cmd: Ps1Command) bool {
    return std.mem.startsWith(u8, cmd.text, "ignored: ") or std.mem.startsWith(u8, cmd.text, "setup: ");
}

fn allocOwned(allocator: std.mem.Allocator, prefix: []const u8, suffix: []const u8) ![]u8 {
    const out = try allocator.alloc(u8, prefix.len + suffix.len);
    @memcpy(out[0..prefix.len], prefix);
    @memcpy(out[prefix.len..], suffix);
    return out;
}

// ==================================================================== //
//  String utilities
// ==================================================================== //

fn isWordChar(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_';
}

fn trimLeft(s: []const u8, comptime chars: []const u8) []const u8 {
    var start: usize = 0;
    while (start < s.len) {
        const ch = s[start];
        var matched = false;
        inline for (chars) |c| {
            if (ch == c) matched = true;
        }
        if (!matched) break;
        start += 1;
    }
    return s[start..];
}

fn trimRight(s: []const u8, comptime chars: []const u8) []const u8 {
    var end = s.len;
    while (end > 0) {
        const ch = s[end - 1];
        var matched = false;
        inline for (chars) |c| {
            if (ch == c) matched = true;
        }
        if (!matched) break;
        end -= 1;
    }
    return s[0..end];
}

fn startsWith(s: []const u8, comptime prefix: []const u8) bool {
    return std.mem.startsWith(u8, s, prefix);
}

fn startsWithIgnoreCase(s: []const u8, comptime prefix: []const u8) bool {
    if (s.len < prefix.len) return false;
    return std.ascii.eqlIgnoreCase(s[0..prefix.len], prefix);
}

fn indexOf(haystack: []const u8, needle: []const u8) ?usize {
    return std.mem.indexOf(u8, haystack, needle);
}

fn indexOfScalar(haystack: []const u8, needle: u8) ?usize {
    return std.mem.indexOfScalar(u8, haystack, needle);
}

