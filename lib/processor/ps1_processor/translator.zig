/// Parse a single raw line into a `Ps1Command`.  Returns null for blank
/// lines.  `owned` tracks the translator allocation used for prefixed
/// comment text ("ignored: ..." / "setup: ...").
fn parseLine(allocator: std.mem.Allocator, raw: []const u8) !?Ps1Command {
    const line = trimRight(raw, " \t\r");
    const stripped = trimLeft(line, " \t");
    if (stripped.len == 0) return null;

    if (stripped[0] == '#') {
        return Ps1Command{
            .kind = .comment,
            .raw = line,
            .text = trimLeft(stripped[1..], " \t"),
        };
    }

    if (startsWith(stripped, "[CmdletBinding(") or
        startsWith(stripped, "param(") or
        startsWith(stripped, "#Requires"))
    {
        return Ps1Command{
            .kind = .comment,
            .raw = line,
            .text = try allocOwned(allocator, "ignored: ", stripped),
        };
    }

    if (indexOf(stripped, "StrictMode") != null or indexOf(stripped, "ErrorActionPreference") != null) {
        return Ps1Command{
            .kind = .comment,
            .raw = line,
            .text = try allocOwned(allocator, "setup: ", stripped),
        };
    }

    if (matchVariable(stripped)) |var_match| {
        return Ps1Command{
            .kind = .variable,
            .raw = line,
            .name = var_match.name,
            .value = var_match.value,
        };
    }

    if (matchIfNotPath(stripped)) |if_match| {
        return Ps1Command{
            .kind = .if_not_path,
            .raw = line,
            .path = if_match.path,
            .body = if_match.body,
        };
    }

    if (matchIfPath(stripped)) |if_match| {
        return Ps1Command{
            .kind = .if_path,
            .raw = line,
            .path = if_match.path,
            .body = if_match.body,
        };
    }

    if (std.mem.eql(u8, stripped, "}")) {
        return Ps1Command{ .kind = .block_end, .raw = line };
    }

    const space_idx = indexOfScalar(stripped, ' ') orelse stripped.len;
    const command = stripped[0..space_idx];
    const args = if (space_idx < stripped.len) stripped[space_idx + 1 ..] else "";

    return Ps1Command{
        .kind = .command,
        .raw = line,
        .command = command,
        .args = args,
    };
}

/// Matches `^\s*\$(\w+)\s*=\s*(.*)`.
fn matchVariable(stripped: []const u8) ?struct { name: []const u8, value: []const u8 } {
    var s = trimLeft(stripped, " \t");
    if (s.len == 0 or s[0] != '$') return null;
    s = s[1..];
    var name_end: usize = 0;
    while (name_end < s.len and isWordChar(s[name_end])) : (name_end += 1) {}
    if (name_end == 0) return null;
    const name = s[0..name_end];
    var rest = trimLeft(s[name_end..], " \t");
    if (rest.len == 0 or rest[0] != '=') return null;
    rest = trimLeft(rest[1..], " \t");
    return .{ .name = name, .value = rest };
}

/// Matches `if (-not (Test-Path <path>)) { <body>` (case-insensitive).
fn matchIfNotPath(stripped: []const u8) ?struct { path: []const u8, body: []const u8 } {
    var s = trimLeft(stripped, " \t");
    if (!startsWithIgnoreCase(s, "if")) return null;
    s = trimLeft(s[2..], " \t");
    if (s.len == 0 or s[0] != '(') return null;
    s = trimLeft(s[1..], " \t");
    if (!startsWithIgnoreCase(s, "-not")) return null;
    s = trimLeft(s[4..], " \t");
    if (s.len == 0 or s[0] != '(') return null;
    s = trimLeft(s[1..], " \t");
    if (!startsWithIgnoreCase(s, "Test-Path")) return null;
    s = s["Test-Path".len..];
    const path_start = trimLeft(s, " \t");
    if (path_start.len == s.len) return null; // no whitespace after Test-Path
    if (findConditionalClose(path_start)) |close| {
        return .{
            .path = trimRight(path_start[0..close.end], " \t"),
            .body = path_start[close.body_start..],
        };
    }
    return null;
}

/// Matches `if (Test-Path <path>) { <body>` (case-insensitive).
fn matchIfPath(stripped: []const u8) ?struct { path: []const u8, body: []const u8 } {
    var s = trimLeft(stripped, " \t");
    if (!startsWithIgnoreCase(s, "if")) return null;
    s = trimLeft(s[2..], " \t");
    if (s.len == 0 or s[0] != '(') return null;
    s = trimLeft(s[1..], " \t");
    if (!startsWithIgnoreCase(s, "Test-Path")) return null;
    s = s["Test-Path".len..];
    const path_start = trimLeft(s, " \t");
    if (path_start.len == s.len) return null; // no whitespace after Test-Path
    if (findCloseParenBrace(path_start)) |close| {
        return .{
            .path = trimRight(path_start[0..close.end], " \t"),
            .body = path_start[close.body_start..],
        };
    }
    return null;
}

const CloseMatch = struct {
    /// End of the captured path (before trailing whitespace / close).
    end: usize,
    /// Position just after the opening `{`.
    body_start: usize,
};

/// Find the earliest `\s*\)\s*\)\s*\{` in `s`, mirroring the non-greedy
/// `(.*?)\s*\)\s*\)\s*\{` of the Python `_RE_IF_NOT`.
fn findConditionalClose(s: []const u8) ?CloseMatch {
    var i: usize = 0;
    while (i < s.len) : (i += 1) {
        var j = i;
        while (j < s.len and (s[j] == ' ' or s[j] == '\t')) j += 1;
        if (j < s.len and s[j] == ')') {
            var k = j + 1;
            while (k < s.len and (s[k] == ' ' or s[k] == '\t')) k += 1;
            if (k < s.len and s[k] == ')') {
                var m = k + 1;
                while (m < s.len and (s[m] == ' ' or s[m] == '\t')) m += 1;
                if (m < s.len and s[m] == '{') {
                    return .{ .end = i, .body_start = m + 1 };
                }
            }
        }
    }
    return null;
}

/// Find the earliest `\s*\)\s*\{` in `s`, mirroring the non-greedy
/// `(.*?)\s*\)\s*\{` of the Python `_RE_IF`.
fn findCloseParenBrace(s: []const u8) ?CloseMatch {
    var i: usize = 0;
    while (i < s.len) : (i += 1) {
        var j = i;
        while (j < s.len and (s[j] == ' ' or s[j] == '\t')) j += 1;
        if (j < s.len and s[j] == ')') {
            var k = j + 1;
            while (k < s.len and (s[k] == ' ' or s[k] == '\t')) k += 1;
            if (k < s.len and s[k] == '{') {
                return .{ .end = i, .body_start = k + 1 };
            }
        }
    }
    return null;
}

