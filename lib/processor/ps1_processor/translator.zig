const std = @import("std");
const types = @import("types.zig");

const Ps1Command = types.Ps1Command;
const CommandType = types.CommandType;

/// Translates Windows PowerShell (.ps1) content to POSIX shell or
/// Makefile recipes.
///
/// Translates Windows PowerShell (.ps1) content. All slice fields
/// on `Ps1Command` point into the source text, except `text` for
/// "ignored: ..."/"setup: ..." comments which are translator-owned and
/// tracked in `allocated` for deinit.
pub const Ps1Translator = struct {
    allocator: std.mem.Allocator,
    commands: std.ArrayListUnmanaged(Ps1Command),
    /// Translator-owned strings (prefixed comment text) freed on deinit.
    allocated: std.ArrayListUnmanaged([]const u8),

    pub fn init(allocator: std.mem.Allocator) Ps1Translator {
        return .{
            .allocator = allocator,
            .commands = .{ .items = &.{}, .capacity = 0 },
            .allocated = .{ .items = &.{}, .capacity = 0 },
        };
    }

    pub fn deinit(self: *Ps1Translator) void {
        for (self.allocated.items) |owned| self.allocator.free(owned);
        self.allocated.deinit(self.allocator);
        self.commands.deinit(self.allocator);
    }

    // ---------------------------------------------------------------- //
    //  Parsing (file I/O handled by main.zig)
    // ---------------------------------------------------------------- //

    /// Parse a blob of PowerShell text into structured commands.
    pub fn parse(self: *Ps1Translator, text: []const u8) !void {
        self.commands.clearAndFree(self.allocator);
        for (self.allocated.items) |owned| self.allocator.free(owned);
        self.allocated.clearRetainingCapacity();

        const converted = try convertBlockComments(self.allocator, text);
        var lines = std.mem.splitScalar(u8, converted, '\n');
        while (lines.next()) |raw_line| {
            if (try parseLine(self.allocator, raw_line)) |cmd| {
                try self.commands.append(self.allocator, cmd);
                if (cmd.kind == .comment and isOwnedComment(cmd)) {
                    try self.allocated.append(self.allocator, cmd.text);
                }
            }
        }
    }

    // ---------------------------------------------------------------- //
    //  Shell output — builds into caller-provided buffer
    // ---------------------------------------------------------------- //

    /// Generate a POSIX shell script into `out`.
    pub fn toShell(self: *const Ps1Translator, shebang: bool, out: *std.ArrayListUnmanaged(u8)) !void {
        if (shebang) {
            try out.appendSlice(self.allocator, "#!/bin/sh\n");
            try out.appendSlice(self.allocator, "# Generated by lib/processor/ps1_processor.translator\n");
            try out.appendSlice(self.allocator, "set -e  # stop on errors\n\n");
        }
        for (self.commands.items) |cmd| {
            try cmdToShellBuf(cmd, out, self.allocator);
        }
    }

    /// Generate a Makefile recipe into `out`.
    pub fn toMakefile(
        self: *const Ps1Translator,
        target: []const u8,
        deps: []const []const u8,
        out: *std.ArrayListUnmanaged(u8),
    ) !void {
        try out.appendSlice(self.allocator, "# Generated by lib/processor/ps1_processor.translator\n\n");
        try out.appendSlice(self.allocator, target);
        if (deps.len > 0) {
            try out.appendSlice(self.allocator, ": ");
            for (deps, 0..) |dep, i| {
                if (i > 0) try out.appendSlice(self.allocator, " ");
                try out.appendSlice(self.allocator, dep);
            }
        } else {
            try out.appendSlice(self.allocator, ":");
        }
        try out.appendSlice(self.allocator, "\n\t@echo \"  PS1GEN  ");
        try out.appendSlice(self.allocator, target);
        try out.appendSlice(self.allocator, "\"\n");

        for (self.commands.items) |cmd| {
            var line_buf: std.ArrayListUnmanaged(u8) = .{ .items = &.{}, .capacity = 0 };
            defer line_buf.deinit(self.allocator);
            try cmdToShellBuf(cmd, &line_buf, self.allocator);
            const shell_line = line_buf.items;

            if (shell_line.len == 0) continue;
            if (shell_line[0] == '#') {
                try out.appendSlice(self.allocator, "\t");
                try out.appendSlice(self.allocator, shell_line);
            } else {
                try out.appendSlice(self.allocator, "\t@");
                for (shell_line) |ch| {
                    if (ch == '$') {
                        try out.appendSlice(self.allocator, "$$");
                    } else {
                        try out.append(self.allocator, ch);
                    }
                }
            }
            try out.append(self.allocator, '\n');
        }
    }
};

// ==================================================================== //
//  Block comment conversion
// ==================================================================== //

/// Convert `<# ... #>` block comments to `#` line comments, matching the
/// Python `re.sub(r"<#(.*?)#>", ...)` with DOTALL.
fn convertBlockComments(allocator: std.mem.Allocator, text: []const u8) ![]const u8 {
    var out = std.ArrayListUnmanaged(u8){ .items = &.{}, .capacity = 0 };
    errdefer out.deinit(allocator);
    var i: usize = 0;
    while (i < text.len) {
        if (text[i] == '<' and i + 1 < text.len and text[i + 1] == '#') {
            const open_end = i + 2;
            if (std.mem.indexOf(u8, text[open_end..], "#>")) |rel| {
                const close_start = open_end + rel;
                const inner = text[open_end..close_start];
                var lines = std.mem.splitScalar(u8, inner, '\n');
                while (lines.next()) |line| {
                    try out.appendSlice(allocator, "# ");
                    try out.appendSlice(allocator, std.mem.trim(u8, line, " \t"));
                    try out.append(allocator, '\n');
                }
                i = close_start + 2;
                continue;
            }
        }
        try out.append(allocator, text[i]);
        i += 1;
    }
    return out.items;
}

